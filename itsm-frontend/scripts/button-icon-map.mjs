/**
 * 把 lucide 图标名解析成 antd 图标名。未知图标直接抛错，不猜。
 * @param {string} lucideName
 * @returns {string}
 */
export function toAntdIcon(lucideName) {
  const antdName = LUCIDE_TO_ANTD[lucideName];
  if (!antdName) {
    throw new Error(
      '未映射的 lucide 图标: ' + lucideName +
      '。请先核对 @ant-design/icons 里的等价图标并补进 LUCIDE_TO_ANTD，不要猜。'
    );
  }
  return antdName;
}
