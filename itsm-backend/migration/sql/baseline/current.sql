DO $verify_baseline$
DECLARE
    target RECORD;
    actual_signature TEXT;
    relation_id OID;
    constraint_count INTEGER;
    expected_default_count INTEGER;
    matching_default_count INTEGER;
    actual_default_count INTEGER;
    policy_count INTEGER;
    policy_using TEXT;
    policy_check TEXT;
    policy_roles OID[];
    policy_command TEXT;
    policy_permissive BOOLEAN;
    actual_rls_enabled BOOLEAN;
    actual_rls_forced BOOLEAN;
    index_ok BOOLEAN;
    retired_table TEXT;
    drifted_execution_id BIGINT;
