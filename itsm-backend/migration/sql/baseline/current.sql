DO $work_item_constraints$
DECLARE
    definition TEXT;
BEGIN
    SELECT pg_get_constraintdef(constraint_record.oid)
    INTO definition
    FROM pg_constraint constraint_record
    JOIN pg_class relation ON relation.oid = constraint_record.conrelid
    JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = current_schema()
      AND relation.relname = 'work_item_number_sequences'
      AND constraint_record.conname = 'work_item_number_sequences_period_check';
    IF definition IS NULL THEN
        ALTER TABLE work_item_number_sequences
            ADD CONSTRAINT work_item_number_sequences_period_check CHECK (period ~ '^[0-9]{6}$');
    ELSIF regexp_replace(definition, '\s+', '', 'g') NOT IN (
        'CHECK(((period)::text~''^[0-9]{6}$''::text))',
        'CHECK((period~''^[0-9]{6}$''::text))'
    ) THEN
        RAISE EXCEPTION 'current baseline work item period constraint mismatch';
    END IF;

    definition := NULL;
    SELECT pg_get_constraintdef(constraint_record.oid)
    INTO definition
    FROM pg_constraint constraint_record
    JOIN pg_class relation ON relation.oid = constraint_record.conrelid
    JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = current_schema()
      AND relation.relname = 'work_item_number_sequences'
      AND constraint_record.conname = 'work_item_number_sequences_last_value_check';
    IF definition IS NULL THEN
        ALTER TABLE work_item_number_sequences
            ADD CONSTRAINT work_item_number_sequences_last_value_check CHECK (last_value BETWEEN 0 AND 999999);
    ELSIF position('last_value' IN definition) = 0 OR position('999999' IN definition) = 0 THEN
        RAISE EXCEPTION 'current baseline work item counter constraint mismatch';
    END IF;
END $work_item_constraints$;

DO $current_rls$
DECLARE
    target RECORD;
    relation_id OID;
    policy_count INTEGER;
    canonical_policy TEXT;
BEGIN
    PERFORM current_setting('app.current_tenant', true);
    FOR target IN
        SELECT * FROM (VALUES
            ('teams', 'direct', true, false, true),
            ('roles', 'direct', true, false, true),
            ('users', 'direct', true, false, true),
            ('sla_policies', 'direct', true, false, false),
            ('tickets', 'direct', false, false, true),
            ('service_catalogs', 'direct', true, false, true),
            ('ci_types', 'direct', true, false, true),
            ('standard_changes', 'direct', true, false, true),
            ('known_errors', 'direct', true, false, true),
            ('sla_alert_rules', 'direct', true, false, true),
            ('tags', 'direct', true, false, true),
            ('departments', 'direct', true, false, true),
            ('ticket_categories', 'direct', true, false, true),
            ('process_bindings', 'direct', true, false, true),
            ('process_definitions', 'direct', true, false, true),
            ('process_deployments', 'direct', true, false, true),
            ('ticket_views', 'direct', true, false, true),
            ('kaf_task_action_ledgers', 'direct', true, true, true),
            ('kaf_task_completion_receipts', 'direct', true, true, true),
            ('incidents', 'work_item', true, false, true),
            ('problems', 'work_item', true, false, true),
            ('changes', 'work_item', true, false, true),
            ('change_approvals', 'change_work_item', false, false, true),
            ('change_approval_chains', 'change_work_item', false, false, true),
            ('change_risk_assessments', 'change_work_item', false, false, true),
            ('change_rollback_plans', 'change_work_item', false, false, true),
            ('change_rollback_executions', 'change_work_item', false, false, true),
            ('change_implementation_plans', 'change_work_item', false, false, true)
        ) AS registry(table_name, policy_kind, rls_enabled, rls_forced, required)
    LOOP
        relation_id := to_regclass(format('%I.%I', current_schema(), target.table_name));
        IF relation_id IS NULL THEN
            IF target.required THEN
                RAISE EXCEPTION 'current baseline required RLS table % is missing', target.table_name;
            END IF;
            CONTINUE;
        END IF;
        SELECT COUNT(*) INTO policy_count FROM pg_policy WHERE polrelid = relation_id;
        IF policy_count <> 0 THEN
            CONTINUE;
        END IF;
        IF target.rls_enabled THEN
            EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', current_schema(), target.table_name);
        ELSE
            EXECUTE format('ALTER TABLE %I.%I DISABLE ROW LEVEL SECURITY', current_schema(), target.table_name);
        END IF;
        IF target.rls_forced THEN
            EXECUTE format('ALTER TABLE %I.%I FORCE ROW LEVEL SECURITY', current_schema(), target.table_name);
        ELSE
            EXECUTE format('ALTER TABLE %I.%I NO FORCE ROW LEVEL SECURITY', current_schema(), target.table_name);
        END IF;
        canonical_policy := 'tenant_isolation_' || target.table_name;
        IF target.policy_kind = 'direct' THEN
            EXECUTE format(
                'CREATE POLICY %I ON %I.%I AS PERMISSIVE FOR ALL TO PUBLIC '
                'USING (tenant_id = NULLIF(current_setting(''app.current_tenant'', true), '''')::bigint) '
                'WITH CHECK (tenant_id = NULLIF(current_setting(''app.current_tenant'', true), '''')::bigint)',
                canonical_policy, current_schema(), target.table_name
            );
        ELSIF target.policy_kind = 'work_item' THEN
            EXECUTE format(
                'CREATE POLICY %I ON %I.%I AS PERMISSIVE FOR ALL TO PUBLIC '
                'USING (EXISTS (SELECT 1 FROM %I.tickets work_item WHERE work_item.id = %I.work_item_id '
                'AND work_item.tenant_id = NULLIF(current_setting(''app.current_tenant'', true), '''')::bigint '
                'AND work_item.deleted_at IS NULL)) '
                'WITH CHECK (EXISTS (SELECT 1 FROM %I.tickets work_item WHERE work_item.id = %I.work_item_id '
                'AND work_item.tenant_id = NULLIF(current_setting(''app.current_tenant'', true), '''')::bigint '
                'AND work_item.deleted_at IS NULL))',
                canonical_policy, current_schema(), target.table_name,
                current_schema(), target.table_name, current_schema(), target.table_name
            );
        ELSIF target.policy_kind = 'change_work_item' THEN
            EXECUTE format(
                'CREATE POLICY %I ON %I.%I AS PERMISSIVE FOR ALL TO PUBLIC '
                'USING (EXISTS (SELECT 1 FROM %I.changes change_record '
                'JOIN %I.tickets work_item ON work_item.id = change_record.work_item_id '
                'WHERE change_record.id = %I.change_id '
                'AND work_item.tenant_id = NULLIF(current_setting(''app.current_tenant'', true), '''')::bigint '
                'AND work_item.deleted_at IS NULL)) '
                'WITH CHECK (EXISTS (SELECT 1 FROM %I.changes change_record '
                'JOIN %I.tickets work_item ON work_item.id = change_record.work_item_id '
                'WHERE change_record.id = %I.change_id '
                'AND work_item.tenant_id = NULLIF(current_setting(''app.current_tenant'', true), '''')::bigint '
                'AND work_item.deleted_at IS NULL))',
                canonical_policy, current_schema(), target.table_name,
                current_schema(), current_schema(), target.table_name,
                current_schema(), current_schema(), target.table_name
            );
        ELSE
            RAISE EXCEPTION 'unsupported current baseline policy kind %', target.policy_kind;
        END IF;
    END LOOP;
END $current_rls$;

