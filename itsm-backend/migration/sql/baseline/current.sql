DO $verify_prepare$
DECLARE
    actual_signature TEXT;
    primary_key_count INTEGER;
    index_ok BOOLEAN;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_extension WHERE extname = 'vector'
    ) THEN
        RAISE EXCEPTION 'current baseline requires the vector extension';
    END IF;

    SELECT string_agg(
        attribute.attname || ':' || format_type(attribute.atttypid, attribute.atttypmod) || ':' ||
        attribute.attnotnull::text || ':' || attribute.attidentity::text,
        ',' ORDER BY attribute.attnum
    )
    INTO actual_signature
    FROM pg_attribute attribute
    JOIN pg_class relation ON relation.oid = attribute.attrelid
    JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = current_schema()
      AND relation.relname = 'vectors'
      AND relation.relkind = 'r'
      AND attribute.attnum > 0
      AND NOT attribute.attisdropped;
    IF actual_signature IS DISTINCT FROM
       'id:bigint:true:d,tenant_id:integer:true:,object_type:text:true:,object_id:integer:true:,embedding:vector(1536):true:,content:text:false:,source:text:false:,created_at:timestamp with time zone:false:' THEN
        RAISE EXCEPTION 'current baseline vectors table definition mismatch';
    END IF;

    SELECT COUNT(*) INTO primary_key_count
    FROM pg_constraint constraint_record
    JOIN pg_class relation ON relation.oid = constraint_record.conrelid
    JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = current_schema()
      AND relation.relname = 'vectors'
      AND constraint_record.contype = 'p'
      AND pg_get_constraintdef(constraint_record.oid) = 'PRIMARY KEY (id)';
    IF primary_key_count <> 1 THEN
        RAISE EXCEPTION 'current baseline vectors primary key mismatch';
    END IF;

    SELECT EXISTS (
        SELECT 1
        FROM pg_index index_record
        JOIN pg_class index_relation ON index_relation.oid = index_record.indexrelid
        JOIN pg_class table_relation ON table_relation.oid = index_record.indrelid
        JOIN pg_namespace namespace ON namespace.oid = table_relation.relnamespace
        JOIN LATERAL unnest(index_record.indkey) WITH ORDINALITY key_column(attnum, ordinal) ON TRUE
        JOIN pg_attribute attribute ON attribute.attrelid = table_relation.oid AND attribute.attnum = key_column.attnum
        WHERE namespace.nspname = current_schema()
          AND table_relation.relname = 'vectors'
          AND index_relation.relname = 'vectors_unique_tenant_obj'
          AND index_record.indisunique AND index_record.indisvalid AND index_record.indisready
          AND index_record.indexprs IS NULL AND index_record.indpred IS NULL
        GROUP BY index_record.indexrelid
        HAVING array_agg(attribute.attname::text ORDER BY key_column.ordinal) = ARRAY['tenant_id', 'object_type', 'object_id']::text[]
    ) INTO index_ok;
    IF NOT index_ok THEN
        RAISE EXCEPTION 'current baseline vectors unique index mismatch';
    END IF;

    SELECT EXISTS (
        SELECT 1
        FROM pg_index index_record
        JOIN pg_class index_relation ON index_relation.oid = index_record.indexrelid
        JOIN pg_class table_relation ON table_relation.oid = index_record.indrelid
        JOIN pg_namespace namespace ON namespace.oid = table_relation.relnamespace
        JOIN pg_am access_method ON access_method.oid = index_relation.relam
        JOIN pg_opclass operator_class ON operator_class.oid = index_record.indclass[0]
        WHERE namespace.nspname = current_schema()
          AND table_relation.relname = 'vectors'
          AND index_relation.relname = 'vectors_embedding_idx'
          AND index_record.indisvalid AND index_record.indisready
          AND NOT index_record.indisunique
          AND access_method.amname = 'ivfflat'
          AND operator_class.opcname = 'vector_cosine_ops'
          AND index_record.indpred IS NULL
          AND index_relation.reloptions @> ARRAY['lists=100']::text[]
    ) INTO index_ok;
    IF NOT index_ok THEN
        RAISE EXCEPTION 'current baseline vectors embedding index mismatch';
    END IF;

    SELECT string_agg(
        attribute.attname || ':' || format_type(attribute.atttypid, attribute.atttypmod) || ':' ||
        attribute.attnotnull::text || ':' || attribute.attidentity::text,
        ',' ORDER BY attribute.attnum
    )
    INTO actual_signature
    FROM pg_attribute attribute
    JOIN pg_class relation ON relation.oid = attribute.attrelid
    JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = current_schema()
      AND relation.relname = 'ai_feedbacks'
      AND relation.relkind = 'r'
      AND attribute.attnum > 0
      AND NOT attribute.attisdropped;
    IF actual_signature IS DISTINCT FROM
       'id:bigint:true:d,created_at:timestamp with time zone:false:,tenant_id:integer:true:,user_id:integer:true:,request_id:text:true:,kind:text:true:,query:text:false:,item_type:text:false:,item_id:integer:false:,useful:boolean:true:,score:integer:false:,notes:text:false:' THEN
        RAISE EXCEPTION 'current baseline ai_feedbacks table definition mismatch';
    END IF;

    SELECT COUNT(*) INTO primary_key_count
    FROM pg_constraint constraint_record
    JOIN pg_class relation ON relation.oid = constraint_record.conrelid
    JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = current_schema()
      AND relation.relname = 'ai_feedbacks'
      AND constraint_record.contype = 'p'
      AND pg_get_constraintdef(constraint_record.oid) = 'PRIMARY KEY (id)';
    IF primary_key_count <> 1 THEN
        RAISE EXCEPTION 'current baseline ai_feedbacks primary key mismatch';
    END IF;

    FOR index_ok IN
        SELECT EXISTS (
            SELECT 1
            FROM pg_index index_record
            JOIN pg_class index_relation ON index_relation.oid = index_record.indexrelid
            JOIN pg_class table_relation ON table_relation.oid = index_record.indrelid
            JOIN pg_namespace namespace ON namespace.oid = table_relation.relnamespace
            JOIN pg_am access_method ON access_method.oid = index_relation.relam
            WHERE namespace.nspname = current_schema()
              AND table_relation.relname = 'ai_feedbacks'
              AND index_relation.relname = required.index_name
              AND index_record.indisvalid AND index_record.indisready
              AND NOT index_record.indisunique
              AND access_method.amname = 'btree'
              AND index_record.indexprs IS NULL AND index_record.indpred IS NULL
              AND pg_get_indexdef(index_record.indexrelid) LIKE '%(' || required.column_name || ')'
        )
        FROM (VALUES
            ('ai_feedbacks_tenant_idx', 'tenant_id'),
            ('ai_feedbacks_created_idx', 'created_at')
        ) AS required(index_name, column_name)
    LOOP
        IF NOT index_ok THEN
            RAISE EXCEPTION 'current baseline ai_feedbacks index mismatch';
        END IF;
    END LOOP;

END $verify_prepare$;

